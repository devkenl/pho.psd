import sys, xml.etree.ElementTree as ET
icons_dir, out = sys.argv[1], sys.argv[2]
names = sys.argv[3].split(',')
NS = '{http://www.w3.org/2000/svg}'
def f(v): return float(v)
def n(x):
    s = ('%.3f' % x).rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s
def to_paths(el):
    t = el.tag.replace(NS, '')
    a = el.attrib
    if t == 'path': return [a['d']]
    if t == 'circle':
        cx, cy, r = f(a['cx']), f(a['cy']), f(a['r'])
        return [f"M{n(cx-r)} {n(cy)}a{n(r)} {n(r)} 0 1 0 {n(2*r)} 0a{n(r)} {n(r)} 0 1 0 {n(-2*r)} 0"]
    if t == 'ellipse':
        cx, cy, rx, ry = f(a['cx']), f(a['cy']), f(a['rx']), f(a['ry'])
        return [f"M{n(cx-rx)} {n(cy)}a{n(rx)} {n(ry)} 0 1 0 {n(2*rx)} 0a{n(rx)} {n(ry)} 0 1 0 {n(-2*rx)} 0"]
    if t == 'line':
        return [f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"]
    if t in ('polyline', 'polygon'):
        pts = a['points'].replace(',', ' ').split()
        pairs = [(pts[i], pts[i+1]) for i in range(0, len(pts), 2)]
        d = 'M' + ' L'.join(f"{x} {y}" for x, y in pairs)
        return [d + ('Z' if t == 'polygon' else '')]
    if t == 'rect':
        x, y, w, h = f(a.get('x', 0)), f(a.get('y', 0)), f(a['width']), f(a['height'])
        rx = f(a.get('rx', a.get('ry', 0))); ry = f(a.get('ry', a.get('rx', 0)))
        if rx == 0:
            return [f"M{n(x)} {n(y)}h{n(w)}v{n(h)}h{n(-w)}Z"]
        return [f"M{n(x+rx)} {n(y)}h{n(w-2*rx)}a{n(rx)} {n(ry)} 0 0 1 {n(rx)} {n(ry)}v{n(h-2*ry)}a{n(rx)} {n(ry)} 0 0 1 {n(-rx)} {n(ry)}h{n(-(w-2*rx))}a{n(rx)} {n(ry)} 0 0 1 {n(-rx)} {n(-ry)}v{n(-(h-2*ry))}a{n(rx)} {n(ry)} 0 0 1 {n(rx)} {n(-ry)}Z"]
    raise SystemExit(f"unsupported element {t}")
def camel(s): return ''.join(p.capitalize() for p in s.split('-'))
lines = []
for name in names:
    root = ET.parse(f"{icons_dir}/{name}.svg").getroot()
    ds = []
    for el in root:
        if el.tag.replace(NS, '') == 'g': raise SystemExit('group in ' + name)
        ds += to_paths(el)
    args = ', '.join('"' + d + '"' for d in ds)
    lines.append(f'    /** Lucide "{name}" */\n    val {camel(name)}: ImageVector by lazy {{ lucide("{name}", {args}) }}\n')
